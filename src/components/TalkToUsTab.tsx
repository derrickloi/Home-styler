import React, { useState, useMemo } from 'react';
import { DiscussionEmbed, CommentCount } from 'disqus-react';
import { 
  MessageSquare, 
  MessagesSquare, 
  Sparkles, 
  ShieldCheck, 
  Users, 
  HelpCircle, 
  Send, 
  CheckCircle2, 
  ExternalLink,
  Info,
  Building,
  HeartHandshake
} from 'lucide-react';

interface DiscussionTopic {
  id: string;
  title: string;
  description: string;
  badge: string;
  slug: string;
}

const TOPICS: DiscussionTopic[] = [
  {
    id: 'homestyler-talk-to-us-main',
    title: 'Talk To Us — General Discussion & Inquiries',
    description: 'Have a question about renovating in Singapore, finding certified contractors, or using HOMESTYLER? Ask our team and community here.',
    badge: 'Main Community Thread',
    slug: 'talk-to-us',
  },
  {
    id: 'homestyler-renovation-advice',
    title: 'Renovation Advice & BOQ Cost Reviews',
    description: 'Get peer reviews on your contractor quotations, carpentry specifications, materials pricing, and timeline estimates.',
    badge: 'Cost & BOQ',
    slug: 'renovation-advice',
  },
  {
    id: 'homestyler-hdb-permits',
    title: 'HDB & BCA Permits, Guidelines & Compliance',
    description: 'Discuss HDB renovation permit applications, approved wet-works waterproofing, electrical LEW endorsements, and structural hacking rules.',
    badge: 'Regulations',
    slug: 'hdb-permits',
  },
  {
    id: 'homestyler-platform-feedback',
    title: 'Platform Feedback & Feature Suggestions',
    description: 'Share your ideas for new features, report bugs, or tell us how we can make Singapore home improvement simpler and safer.',
    badge: 'Feedback',
    slug: 'feedback',
  },
];

export const TalkToUsTab: React.FC = () => {
  const [selectedTopicId, setSelectedTopicId] = useState<string>('homestyler-talk-to-us-main');
  const [useSsoConfig, setUseSsoConfig] = useState<boolean>(false);

  // Active topic
  const currentTopic = useMemo(() => {
    return TOPICS.find((t) => t.id === selectedTopicId) || TOPICS[0];
  }, [selectedTopicId]);

  // Construct absolute URL for Disqus on Vercel or current deployment
  const baseUrl = useMemo(() => {
    if (typeof window !== 'undefined' && window.location.origin) {
      return window.location.origin;
    }
    return 'https://homestyler-project.vercel.app';
  }, []);

  const article = useMemo(() => {
    return {
      url: `${baseUrl}/${currentTopic.slug}`,
      id: currentTopic.id,
      title: `${currentTopic.title} | HOMESTYLER Singapore`,
    };
  }, [baseUrl, currentTopic]);

  // Disqus configuration following user code chunk requirements
  const disqusConfig = useMemo(() => {
    if (useSsoConfig) {
      return {
        url: article.url,
        identifier: article.id,
        title: article.title,
        language: 'en',
        remoteAuthS3: '', // Generated by your server for SSO
        apiKey: '', // API key generated from disqus.com/api/applications/
        sso: {
          name: 'HOMESTYLER',
          button: `${baseUrl}/favicon.png`,
          icon: `${baseUrl}/favicon.png`,
          url: `${baseUrl}/login`,
          logout: `${baseUrl}/logout`,
          profile_url: `${baseUrl}/profile/{username}`,
          width: '800',
          height: '400',
        },
      };
    }

    return {
      url: article.url,
      identifier: article.id,
      title: article.title,
      language: 'en',
    };
  }, [article, useSsoConfig, baseUrl]);

  return (
    <div className="space-y-6 animate-in fade-in duration-200">
      {/* Top Banner Header */}
      <div className="bg-gradient-to-br from-neutral-900 via-neutral-950 to-neutral-900 text-white rounded-2xl p-5 sm:p-7 shadow-sm border border-neutral-800">
        <div className="max-w-3xl">
          <div className="flex items-center gap-2 mb-2">
            <span className="text-[11px] font-extrabold bg-amber-400 text-neutral-950 px-2.5 py-0.5 rounded tracking-wide uppercase flex items-center gap-1">
              <MessageSquare className="w-3.5 h-3.5 text-neutral-950" />
              Talk To Us
            </span>
            <span className="text-xs text-neutral-400 flex items-center gap-1">
              <ShieldCheck className="w-3.5 h-3.5 text-emerald-400" />
              Verified Community Discussion
            </span>
          </div>

          <h2 className="text-2xl sm:text-3xl font-extrabold font-display text-white tracking-tight">
            Talk To Us — Homeowner &amp; Contractor Forum
          </h2>
          <p className="text-xs sm:text-sm text-neutral-300 mt-1.5 leading-relaxed">
            Welcome to the official HOMESTYLER community. Have a question about your renovation, want advice on contractor quotations, or want to share your project experience? Ask below using our embedded Disqus discussion forum.
          </p>

          {/* Quick stats & status bar */}
          <div className="mt-4 pt-4 border-t border-neutral-800/80 flex flex-wrap items-center gap-4 text-xs text-neutral-300">
            <div className="flex items-center gap-1.5 bg-neutral-800/80 px-2.5 py-1 rounded-lg border border-neutral-700/60">
              <span className="text-neutral-400">Forum Shortname:</span>
              <span className="font-mono text-amber-300 font-bold">laura-disqus-com</span>
            </div>

            <div className="flex items-center gap-1.5 bg-neutral-800/80 px-2.5 py-1 rounded-lg border border-neutral-700/60">
              <MessagesSquare className="w-3.5 h-3.5 text-amber-400" />
              <CommentCount
                shortname="laura-disqus-com"
                config={{
                  url: article.url,
                  identifier: article.id,
                  title: article.title,
                }}
              >
                Comments
              </CommentCount>
            </div>

            <div className="flex items-center gap-1.5 text-emerald-400 font-medium text-[11px]">
              <CheckCircle2 className="w-3.5 h-3.5" />
              <span>Optimized for Vercel Deployment</span>
            </div>
          </div>
        </div>
      </div>

      {/* Discussion Channel Selector */}
      <div className="bg-white rounded-xl border border-neutral-200 p-4 shadow-2xs">
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 mb-3">
          <div>
            <h3 className="text-sm sm:text-base font-bold font-display text-neutral-950 flex items-center gap-1.5">
              <Sparkles className="w-4 h-4 text-amber-600" />
              <span>Select Discussion Channel</span>
            </h3>
            <p className="text-xs text-neutral-500">
              Pick a topic to view its dedicated discussion thread and comment count.
            </p>
          </div>

          {/* SSO toggle option */}
          <button
            type="button"
            onClick={() => setUseSsoConfig(!useSsoConfig)}
            className={`text-xs font-semibold px-3 py-1.5 rounded-lg border transition-all cursor-pointer self-start sm:self-auto ${
              useSsoConfig
                ? 'bg-amber-100 text-amber-900 border-amber-300 font-bold'
                : 'bg-neutral-50 text-neutral-600 border-neutral-200 hover:bg-neutral-100'
            }`}
          >
            {useSsoConfig ? '✓ SSO Config Mode Active' : 'Enable SSO Config Mode'}
          </button>
        </div>

        <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-2.5">
          {TOPICS.map((topic) => {
            const isSelected = topic.id === selectedTopicId;
            return (
              <button
                key={topic.id}
                onClick={() => setSelectedTopicId(topic.id)}
                className={`text-left p-3 rounded-xl border transition-all cursor-pointer flex flex-col justify-between ${
                  isSelected
                    ? 'bg-neutral-900 text-white border-neutral-900 shadow-xs'
                    : 'bg-neutral-50 hover:bg-white text-neutral-900 border-neutral-200 hover:border-neutral-300'
                }`}
              >
                <div>
                  <span className={`text-[10px] font-extrabold uppercase px-1.5 py-0.5 rounded tracking-wider ${
                    isSelected ? 'bg-amber-400 text-neutral-950' : 'bg-neutral-200 text-neutral-700'
                  }`}>
                    {topic.badge}
                  </span>
                  <h4 className="text-xs sm:text-sm font-bold mt-1.5 font-display line-clamp-1">
                    {topic.title.split('—')[0].trim()}
                  </h4>
                  <p className={`text-[11px] mt-1 line-clamp-2 leading-relaxed ${
                    isSelected ? 'text-neutral-300' : 'text-neutral-500'
                  }`}>
                    {topic.description}
                  </p>
                </div>

                <div className={`mt-2 pt-2 border-t text-[11px] font-semibold flex items-center justify-between ${
                  isSelected ? 'border-neutral-800 text-amber-400' : 'border-neutral-200 text-neutral-500'
                }`}>
                  <span className="truncate">View Thread</span>
                  <CommentCount
                    shortname="laura-disqus-com"
                    config={{
                      url: `${baseUrl}/${topic.slug}`,
                      identifier: topic.id,
                      title: topic.title,
                    }}
                  >
                    Comments
                  </CommentCount>
                </div>
              </button>
            );
          })}
        </div>
      </div>

      {/* Main Disqus Embed Card */}
      <div className="bg-white rounded-2xl border border-neutral-200 p-5 sm:p-7 shadow-xs">
        {/* Active Thread Meta */}
        <div className="pb-4 mb-5 border-b border-neutral-100 flex flex-col sm:flex-row sm:items-center justify-between gap-2">
          <div>
            <div className="flex items-center gap-2">
              <span className="text-xs font-extrabold text-amber-800 bg-amber-50 px-2 py-0.5 rounded border border-amber-200">
                Active Thread
              </span>
              <span className="text-xs font-mono text-neutral-400">
                id: {article.id}
              </span>
            </div>
            <h3 className="text-lg sm:text-xl font-bold font-display text-neutral-950 mt-1">
              {currentTopic.title}
            </h3>
            <p className="text-xs text-neutral-600 mt-0.5">
              {currentTopic.description}
            </p>
          </div>

          <div className="text-right text-xs text-neutral-500 shrink-0">
            <span className="text-[10px] uppercase font-bold text-neutral-400 block">Total Comments</span>
            <div className="font-bold text-neutral-900 text-sm">
              <CommentCount
                shortname="laura-disqus-com"
                config={disqusConfig}
              >
                0 Comments
              </CommentCount>
            </div>
          </div>
        </div>

        {/* Embedded Disqus Forum */}
        <div className="min-h-[350px]">
          <DiscussionEmbed
            key={article.id}
            shortname="laura-disqus-com"
            config={disqusConfig}
          />
        </div>
      </div>

      {/* Community Guidelines & Direct Support Card */}
      <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
        <div className="bg-neutral-50 rounded-xl border border-neutral-200 p-4 sm:p-5">
          <div className="flex items-center gap-2 mb-2">
            <ShieldCheck className="w-4 h-4 text-emerald-600" />
            <h4 className="text-sm font-bold text-neutral-900 font-display">
              Community Etiquette &amp; Safety
            </h4>
          </div>
          <ul className="text-xs text-neutral-600 space-y-1.5 list-disc list-inside leading-relaxed">
            <li>Keep discussions constructive, respectful, and focused on Singapore renovation.</li>
            <li>Do not post personal phone numbers, bank accounts, or confidential quotations.</li>
            <li>Verify all contractor UEN registration with ACRA and HDB RRC before signing contracts.</li>
            <li>Report suspicious spam or unsolicited middleman promotions.</li>
          </ul>
        </div>

        <div className="bg-amber-50/70 rounded-xl border border-amber-200/80 p-4 sm:p-5 flex flex-col justify-between">
          <div>
            <div className="flex items-center gap-2 mb-2">
              <HeartHandshake className="w-4 h-4 text-amber-800" />
              <h4 className="text-sm font-bold text-neutral-950 font-display">
                Need Direct Assistance with a Project?
              </h4>
            </div>
            <p className="text-xs text-neutral-700 leading-relaxed">
              If you require immediate help connecting with certified HDB contractors, resolving quotation disputes, or getting competitive bids for your home, our platform coordinators are here to assist.
            </p>
          </div>

          <div className="mt-3 pt-3 border-t border-amber-200/60 flex items-center justify-between text-xs">
            <span className="text-neutral-600 font-medium">Free Homeowner Support</span>
            <a
              href="mailto:support@homestyler.sg"
              className="text-amber-800 font-bold hover:underline"
            >
              support@homestyler.sg
            </a>
          </div>
        </div>
      </div>
    </div>
  );
};
